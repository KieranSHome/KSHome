const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch();
  const base=process.env.BLOCKS_PREVIEW || 'https://codex-kiwiii-blocks.kshome-7wd.pages.dev';
  const page=await browser.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/Projects/blocks/');
  await page.getByRole('button',{name:'Start game',exact:true}).click();
  await page.locator('#board').press('Space');
  assert(Number(await page.locator('#score').textContent())>0,'hard drop awards score in browser');
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  const pausedScore=await page.locator('#score').textContent();
  await page.getByRole('button',{name:'Drop',exact:false}).click();
  assert.equal(await page.locator('#score').textContent(),pausedScore,'pause blocks touch input');
  await page.getByRole('button',{name:'Restart',exact:true}).click();
  assert.equal(await page.locator('#score').textContent(),'0');
  await page.screenshot({path:'blocks-desktop.png',fullPage:true});
  const api=page.request;
  assert.equal((await api.get(base+'/api/blocks')).status(),200);
  assert.equal((await api.post(base+'/api/blocks',{headers:{Origin:'https://evil.invalid'},data:{action:'start'}})).status(),403);
  const session=await api.post(base+'/api/blocks',{headers:{Origin:base},data:{action:'start'}});
  assert.equal(session.status(),201);
  const {token}=await session.json();
  await new Promise(resolve=>setTimeout(resolve,3200));
  const body={token,name:'Preview check',score:100,lines:1};
  assert.equal((await api.post(base+'/api/blocks',{headers:{Origin:base},data:body})).status(),201,'D1 save works');
  assert.equal((await api.post(base+'/api/blocks',{headers:{Origin:base},data:body})).status(),400,'D1 replay rejected');
  const scores=await (await api.get(base+'/api/blocks')).json();
  assert(scores.scores.some(row=>row.name==='Preview check'&&row.score===100),'score persisted across requests');
  await page.goto(base+'/Projects/');
  await page.waitForFunction(()=>document.getElementById('leaderboard-status').textContent.startsWith('Shared scores'));
  assert(await page.locator('#leaderboard li').count()>0,'Projects shows shared leaderboard');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await mobile.route('**/api/blocks',route=>route.abort());
  await mobile.goto(base+'/Projects/blocks/');
  await mobile.getByRole('button',{name:'Start game',exact:true}).tap();
  await mobile.getByRole('button',{name:'Drop',exact:false}).tap();
  assert(Number(await mobile.locator('#score').textContent())>0,'touch game works without API');
  await mobile.waitForFunction(()=>document.getElementById('leaderboard-status').textContent.includes('unavailable'));
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'no mobile overflow');
  await mobile.screenshot({path:'blocks-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();console.log('Live desktop, mobile, offline leaderboard and D1 persistence checks passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
